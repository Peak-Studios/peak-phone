"""Runtime UI workflows with synthetic RPCs. Screenshots are review evidence, not FiveM certification."""
from pathlib import Path
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from functools import partial
from threading import Thread
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'artifacts/kilogram-redesign';OUT.mkdir(parents=True,exist_ok=True)
class Quiet(SimpleHTTPRequestHandler):
 extensions_map={**SimpleHTTPRequestHandler.extensions_map,'.mjs':'text/javascript'}
 def log_message(self,*args):pass
server=ThreadingHTTPServer(('127.0.0.1',0),partial(Quiet,directory=str(ROOT)))
Thread(target=server.serve_forever,daemon=True).start()
checks=[]
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True)
 page=browser.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.route('https://i.imgur.com/kg-fixture.svg',lambda route:route.fulfill(path=str(ROOT/'web/public/duo/wallpaper.svg'),content_type='image/svg+xml'))
 def check(name,condition=True):
  assert condition,name
  checks.append(name)
 def js(code):return page.evaluate(code)
 def settle():page.wait_for_timeout(130)
 def shot(name):page.locator('#duo').screenshot(path=str(OUT/(name+'.png')))
 def click(label):page.get_by_role('button',name=label,exact=True).click();settle()
 for label,width,height in [('folded',320,680),('unfolded',720,680),('split',240,680)]:
  page.set_viewport_size({'width':width,'height':height})
  page.goto(f'http://127.0.0.1:{server.server_port}/tests/kilogram/fixture.html');page.wait_for_function('window.ready');settle()
  for nav in ['home','me','search','inbox','activity','saved','reels','live']:
   js(f"app.navigate('{nav}')");settle();shot(label+'-'+nav)
   check(label+' '+nav+' has no app overflow',js("app.element.scrollWidth<=app.element.clientWidth+1"))
   check(label+' '+nav+' dark surface',js("getComputedStyle(app.element).backgroundColor==='rgb(12, 16, 20)'"))
   check(label+' '+nav+' five dock actions',page.locator('.kg-nav>.kg-icon').count()==5)
  js("app.navigate('me')");settle();click('New highlight')
  page.get_by_placeholder('Favourite moments').fill('Weekend')
  page.locator('.kg-archive-tile').nth(1).click();click('Save highlight');settle()
  check(label+' selected expired story saved',js("requests.some(r=>r.event==='Social/SaveHighlight'&&r.data.StoryIds.includes(19))"))
  click('Open highlight Weekend');click('Edit highlight');page.get_by_placeholder('Favourite moments').fill('Weekend memories');click('Save highlight');settle()
  check(label+' highlight rename persists',page.get_by_role('button',name='Open highlight Weekend memories',exact=True).count()==1)
  click('Open highlight Weekend memories');click('View highlight')
  check(label+' expired highlight plays',page.locator('.kg-story-stage').count()==1);shot(label+'-highlight')
  click('Close story');js('app.storyArchive()');settle();shot(label+'-archive')
  page.locator('.kg-archive-tile').nth(1).click();settle()
  check(label+' private expired archive plays',page.locator('.kg-story-stage').count()==1)
  click('Close story');js("app.compose('image')");settle();shot(label+'-composer')
  check(label+' composer fields use dark material',js("getComputedStyle(document.querySelector('.kg-composer textarea')).backgroundImage==='none'"))
  js('app.closeSheet()')
  js("app.navigate('me')");settle();click('Gift wallet');settle();shot(label+'-wallet')
  check(label+' profile wallet shows server-priced coin packs without a live',page.get_by_role('radio',name='100 coins · $1,000 in-game',exact=True).is_visible())
  check(label+' profile wallet hides gifts until a live is joined',page.locator('.kg-gift-choice').count()==0)
  check(label+' wallet panel fits width',js("app.sheet.panel.scrollWidth<=app.sheet.panel.clientWidth+1"))
  check(label+' wallet uses dark identity',js("getComputedStyle(document.querySelector('.kg-wallet-balance')).backgroundColor!=='rgb(255, 255, 255)'"))
  check(label+' first coin pack selected',page.get_by_role('radio',name='100 coins · $1,000 in-game',exact=True).get_attribute('aria-checked')=='true')
  click('Buy 100 coins · $1,000 in-game');settle()
  check(label+' coin purchase uses KiloGram wallet route',js("requests.some(r=>r.event==='KiloLive/PurchaseCoins'&&r.data.PackId==='starter')"))
  check(label+' purchased wallet balance refreshes',page.locator('.kg-wallet-balance strong').inner_text()=='200')
  check(label+' wallet uses local dock blur',page.locator('.kg-wallet-sheet>.duo-surface-blur .duo-surface-replica').count()==1)
  click('Withdraw');settle()
  page.get_by_role('spinbutton',name='Coins to withdraw',exact=True).fill('40');settle()
  check(label+' withdrawal previews bank payout',page.locator('.kg-wallet-preview').inner_text()=='You receive $40 · 160 coins remain')
  click('Withdraw to bank');settle()
  check(label+' withdrawal works outside a live',js("requests.some(r=>r.event==='KiloLive/CashOut'&&r.data.Coins===40&&!r.data.SessionId)"))
  check(label+' withdrawal refreshes balance',page.locator('.kg-wallet-balance strong').inner_text()=='160')
  click('Withdraw all');settle()
  check(label+' withdraw all fills available coins',page.get_by_role('spinbutton',name='Coins to withdraw',exact=True).input_value()=='160')
  shot(label+'-wallet-withdraw')
  js('app.closeSheet()')
  js("app.live.session={role:'viewer',id:'fixture-live',token:'fixture-token',author:{name:'Jordan Lee'}};app.liveWallet()")
  settle();shot(label+'-gifts')
  check(label+' gift grid uses server catalogue',page.locator('.kg-gift-grid .kg-gift-choice').count()==4)
  click('Send Rose · 5 coins');settle()
  check(label+' gift uses live route and session',js("requests.some(r=>r.event==='KiloLive/Gift'&&r.data.GiftId==='rose'&&r.data.SessionId==='fixture-live')"))
  js('app.live.session=null')
  js('app.comments({id:12,author:{id:2,name:"Jordan Lee",handle:"jordan.lee"},comments:1})');settle();shot(label+'-comments')
  page.get_by_role('textbox',name='Add a comment',exact=True).fill('Nice sunset');click('Post comment')
  check(label+' comment reaches server route',js("requests.some(r=>r.event==='Social/CreateComment'&&r.data.Id===12&&r.data.Body==='Nice sunset')"))
  check(label+' confirmed comment appears in sheet',page.locator('.kg-comment-copy p').filter(has_text='Nice sunset').count()==1)
  js('app.closeSheet()')
  js('app.editProfile()');settle();shot(label+'-edit-profile');js('app.closeSheet()')
  js('app.settings()');settle();shot(label+'-settings');js('app.closeSheet()')
  for name,code in [('create-menu','app.createMenu()'),('feed-menu','app.feedMenu()'),('blocked','app.blockedList()'),('report',"app.report({id:2,name:'Jordan',handle:'jordan'}, {id:12})"),('delete-account','app.deleteAccount()'),('live-setup','app.goLiveSheet()')]:
   js(code);settle();shot(label+'-'+name)
   check(label+' '+name+' panel fits width',js("app.sheet.panel.scrollWidth<=app.sheet.panel.clientWidth+1"))
   js('app.closeSheet()')
  js("app.navigate('me')");settle();click('Open highlight Weekend memories');click('Delete highlight');click('Delete highlight');settle()
  check(label+' highlight removed',page.get_by_role('button',name='Open highlight Weekend memories',exact=True).count()==0)
  js('app.showProfile(2)');settle();shot(label+'-other-profile')
  js("app.chat({id:2,name:'Jordan Lee'})");settle();shot(label+'-chat')
  check(label+' chat composer accessible',page.get_by_role('textbox',name='Message',exact=True).is_visible())
  js("app.navigate('inbox')");settle();page.locator('.kg-app>.kg-body').get_by_placeholder('Search messages').fill('unmatched')
  check(label+' message search filters',page.locator('.kg-app>.kg-body .gx-conversation-list>.gx-person:visible').count()==0)
  js('app.newMessage()');settle();shot(label+'-new-message');js('app.closeSheet()')
  js("app.liveScreen=true;app.buildLiveUI()");settle();shot(label+'-broadcast')
  js("app.renderLiveEnded({role:'host',reason:'Live connection timed out.',session:{unique_viewers:2,likes:3}})")
  settle();shot(label+'-broadcast-ended')
  check(label+' ended live keeps dark surface',js("getComputedStyle(document.querySelector('.kg-live-ended')).backgroundColor==='rgb(9, 10, 12)'"))
  check(label+' ended live has no overflow',js("app.element.scrollWidth<=app.element.clientWidth+1"))
  js('app.liveScreen=false')
  js('app.me=null;app.welcome()');settle();shot(label+'-welcome')
 check('No uncaught browser errors',not errors)
 browser.close()
server.shutdown()
(OUT/'browser-results.json').write_text(json.dumps({'checks':checks,'errors':errors},indent=2))
print(f'PASS {len(checks)} browser checks; screenshots in {OUT}')
